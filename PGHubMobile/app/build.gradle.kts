// Read Supabase credentials from local.properties (git-ignored) so that no
// secret is ever hardcoded in source. Values are exposed to app code via
// BuildConfig fields. Empty fallbacks keep the build working even before the
// developer fills in local.properties (screens then show an error state).
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun secret(key: String): String = (localProps.getProperty(key) ?: "").trim()

